## 进阶示例：错误处理、索引位与构造、局部 IJ、二十面体面、网格环
##
## 使用: nim c --path:src -r examples/example_advanced.nim

import std/[strformat, sequtils]
import h3nim

let 单元 = 字符串转单元("8928308280fffff")
echo &"基准单元: {单元转字符串(单元)}"

# ── 1. 错误处理 ──────────────────────────────

echo "\n=== 1. 错误处理 ==="

# 便捷封装（值形式）失败时抛出 H3异常
try:
  discard 字符串转单元("not-a-valid-h3-index")
  echo "非法字符串：未抛异常（不应发生）"
except H3异常 as e:
  echo &"非法字符串 → H3异常: {e.错误}"

# 需要错误码而不抛异常时，使用底层指针重载
var 经纬 = 度转经纬度(0.0, 0.0)
var 输出: H3索引
let 错误 = 经纬度转单元(addr 经纬, 99.cint, addr 输出)  # res 99 非法
echo &"非法分辨率错误码: {uint32(错误)}, 描述: {描述H3错误(错误)}"
if not 是否成功(错误): echo "是否成功 = false"

# ── 2. 索引位与构造（往返）───────────────────

echo "\n=== 2. 索引位与构造 ==="
let 分辨率 = 获取分辨率(单元)
echo &"分辨率: {分辨率}, 基单元号: {获取基单元号(单元)}"
var 数字 = newSeq[cint](分辨率)
for r in 1 .. 分辨率:
  discard 获取索引位(单元, r.cint, addr 数字[r - 1])
echo "索引位: ", 数字

var 重建: H3索引
if 构造单元(分辨率.cint, 获取基单元号(单元), addr 数字[0], addr 重建) == 成功:
  echo &"由位构造: {单元转字符串(重建)} (与原单元一致: {重建 == 单元})"

# ── 3. 局部 IJ 坐标 ─────────────────────────

echo "\n=== 3. 局部 IJ 坐标 ==="
var 邻居: array[7, H3索引]
if 网格圆盘(单元, 1, addr 邻居[0]) == 成功 and 邻居[1] != H3空:
  var ij: 坐标IJ
  if 单元转局部IJ(单元, 邻居[1], 0, addr ij) == 成功:
    echo &"邻居 {单元转字符串(邻居[1])} 的局部 IJ: i={ij.i}, j={ij.j}"
    var 还原: H3索引
    if 局部IJ转单元(单元, addr ij, 0, addr 还原) == 成功:
      echo &"IJ → 单元 还原: {单元转字符串(还原)} (一致: {还原 == 邻居[1]})"

# ── 4. 二十面体面 ───────────────────────────

echo "\n=== 4. 二十面体面 ==="
var 最大面: cint
if 最大面数(单元, addr 最大面) == 成功:
  var 面集 = newSeq[cint](最大面.int)
  if 获取二十面体面(单元, addr 面集[0]) == 成功:
    echo &"该单元最多跨越 {最大面} 个面"
    for 面 in 面集:
      if 面 >= 0:
        echo &"  面 {面}"

# ── 5. 网格环（hollow ring）─────────────────

echo "\n=== 5. 网格环 ==="
for k in 1 .. 2:
  var 环大小: int64
  if 最大网格环数(k.cint, addr 环大小) == 成功:
    var 环 = newSeq[H3索引](环大小)
    if 网格环(单元, k.cint, addr 环[0]) == 成功:
      echo &"k={k}: 环上 {环.countIt(it != H3空)} 个单元"

# ── 6. 多边形单元迭代器（输出无空洞）────────

echo "\n=== 6. 多边形单元迭代器 ==="
block:
  const 边数 = 4
  var 环 = 地理环(
    顶点数: 边数,
    顶点: cast[ptr 经纬度](alloc0(sizeof(经纬度) * 边数)),
  )
  let 矩形顶点 = cast[ptr array[边数, 经纬度]](环.顶点)
  矩形顶点[0] = 度转经纬度(37.77, -122.43)
  矩形顶点[1] = 度转经纬度(37.77, -122.41)
  矩形顶点[2] = 度转经纬度(37.79, -122.41)
  矩形顶点[3] = 度转经纬度(37.79, -122.43)
  var 多边形 = 地理多边形(外环: 环, 孔数: 0, 孔: nil)

  var 迭代 = 初始化多边形迭代(addr 多边形, 9.cint, 0)
  var 数量 = 0
  while 迭代.单元 != H3空 and 数量 < 5:
    echo &"  单元 {数量}: {单元转字符串(迭代.单元)}"
    步进多边形迭代(addr 迭代)
    inc 数量
  if 迭代.错误 != 成功:
    echo &"  迭代错误: {描述H3错误(迭代.错误)}"
  销毁多边形迭代(addr 迭代)
  dealloc(环.顶点)

echo "\n✅ 进阶示例完成"

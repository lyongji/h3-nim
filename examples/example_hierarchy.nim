## 层级与路径示例：父级/子级、紧凑/解紧凑、网格路径、有向边
##
## 使用: nim c --path:src -r examples/example_hierarchy.nim

import std/[strformat, sequtils]
import h3nim

let 北京 = 度转经纬度(39.9042, 116.4074)
let 单元 = 北京.经纬度转单元(10)
echo &"原始单元 (res 10): {单元转字符串(单元)}"

# ── 1. 父级 → 子级 遍历 ────────────────────

echo "\n=== 父级 → 子级 ==="
let 父 = 单元.单元转父级(8)  # 升一级到 res 8
echo &"父级 (res 8): {单元转字符串(父)}"
echo &"res 8 → res 10 子级总数: {单元转子级数(父, 10)}"

# 中心子级
let 中子 = 父.单元转中心子级(10)
echo &"中心子级 (res 10): {单元转字符串(中子)}"

# 子级位置（childPos）往返
let 位 = 单元转子级位置(中子, 8)
echo &"中心子级位置: {位} → 还原: {单元转字符串(子级位置转单元(位, 父, 10))}"

# ── 2. 迭代子单元（手动迭代器）─────────────

echo "\n=== 迭代子单元（前 5 个）==="
var 迭代 = 初始化父级迭代(父, 10)
var 计数 = 0
while 计数 < 5:
  if 迭代.单元 == H3空: break
  echo &"  子 {计数}: {单元转字符串(迭代.单元)}"
  步进子级迭代(addr 迭代)
  计数.inc

# ── 3. compact / uncompact ──────────────────

echo "\n=== 紧凑/解紧凑 ==="
# 拿 res 10 的 7 个单元（k-ring）
let 邻居 = 网格圆盘(单元, 1)
# compact：将 7 个 res 10 单元压缩为更高层级
let 紧凑 = 紧凑单元(邻居)
echo &"紧凑前: {邻居.len} 个单元 → 紧凑后: {紧凑.len} 个"
for i, c in 紧凑:
  echo &"  紧凑 {i}: res {获取分辨率(c)} {单元转字符串(c)}"

# 解紧凑回 res 10
let 解 = 解紧凑单元(紧凑, 10)
echo &"解紧凑后: {解.len} 个单元 (期望 7)"

# ── 4. 网格距离 & 路径 ─────────────────────

echo "\n=== 网格距离与路径 ==="
let 上海 = 度转经纬度(31.2304, 121.4737)
let 单元2 = 上海.经纬度转单元(10)

echo &"北京→上海: {网格距离(单元, 单元2)} 步 (网格距离)"
let 路径 = 网格路径单元(单元, 单元2)
echo &"路径长度: {路径.len} 个单元"
echo &"  起点: {单元转字符串(路径[0])}"
echo &"  终点: {单元转字符串(路径[^1])}"

# ── 5. 有向边 ─────────────────────────────

echo "\n=== 有向边 ==="
if 邻居.len > 1 and 邻居[1] != H3空:
  let 边 = 单元转有向边(单元, 邻居[1])
  echo &"边: {单元转字符串(边)}"
  echo &"  是否有效有向边: {是否有效有向边(边)}"
  echo &"  起点: {单元转字符串(获取有向边起点(边))}"
  echo &"  终点: {单元转字符串(获取有向边终点(边))}"

  let (原点, 目标) = 有向边转单元(边)
  echo &"  有向边转单元: {单元转字符串(原点)} → {单元转字符串(目标)}"
  echo &"  有向边边界顶点数: {有向边转边界(边).顶点数}"

  let 反转边 = 反转有向边(边)
  echo &"  反转后起点→终点: {单元转字符串(获取有向边起点(反转边))} → " &
       $单元转字符串(获取有向边终点(反转边))

# ── 6. 顶点 ───────────────────────────────

echo "\n=== 顶点 ==="
let 顶点集 = 单元转顶点集(单元)
echo &"顶点数: {顶点集.countIt(it != H3空)}"
for i, 顶点 in 顶点集:
  if 顶点 != H3空:
    let (纬度, 经度) = 顶点转经纬度(顶点).经纬度转度()
    echo &"  顶点 {i}: ({纬度:.6f}, {经度:.6f})"

# ── 7. 五边形检测 ─────────────────────────

echo "\n=== 五边形 ==="
let 五边 = 获取五边形(5)
echo "res 5 五边形:"
if 五边.len > 0:
  echo &"  0: {单元转字符串(五边[0])}"

echo "\n✅ 层级与路径示例完成"

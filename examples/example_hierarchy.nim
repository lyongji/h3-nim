## 层级与路径示例：父级/子级、紧凑/解紧凑、网格路径、有向边
##
## 使用: nim c --path:src -r examples/example_hierarchy.nim

import std/[math, strformat, sequtils]
import h3nim

let 北京 = 度转经纬度(39.9042, 116.4074)
let 单元 = 北京.经纬度转单元(10)
echo &"原始单元 (res 10): {单元转字符串(单元)}"

# ── 1. 父级 → 子级 遍历 ────────────────────

echo "\n=== 父级 → 子级 ==="
let 父 = 单元.单元转父级(8)  # 升一级到 res 8
echo &"父级 (res 8): {单元转字符串(父)}"

# 子级数
var 子级数: int64
if 单元转子级数(父, 10, addr 子级数) == 成功:
  echo &"res 8 → res 10 子级总数: {子级数}"

# 中心子级
let 中子 = 父.单元转中心子级(10)
echo &"中心子级 (res 10): {单元转字符串(中子)}"

# ── 2. 迭代子单元（手动迭代器）─────────────

echo "\n=== 迭代子单元（前 5 个）==="
var 迭代 = 初始化父级迭代(父, 10)
var 计数 = 0
while 计数 < 5:
  if 迭代.单元 == H3空: break
  echo &"  子 {计数}: {单元转字符串(迭代.单元)}"
  步进子级迭代(addr 迭代)
  计数.inc

# ── 3. compact / uncompact ──────────────────

echo "\n=== 紧凑/解紧凑 ==="
# 拿 res 10 的 7 个单元（k-ring）
var 邻居: array[7, H3索引]
if 网格圆盘(单元, 1, addr 邻居[0]) == 成功:
  # compact：将 7 个 res 10 单元压缩为更高层级
  var 紧凑: array[7, H3索引]
  let 紧错 = 紧凑单元(addr 邻居[0], addr 紧凑[0], 7)
  if 紧错 == 成功:
    let 有效紧 = 紧凑.countIt(it != H3空)
    echo &"紧凑前: 7 个单元 → 紧凑后: {有效紧} 个"
    for i in 0..<有效紧:
      echo &"  紧凑 {i}: res {获取分辨率(紧凑[i])} {单元转字符串(紧凑[i])}"

    # 解紧凑回 res 10
    var 解大小: int64
    if 解紧凑单元数(addr 紧凑[0], 7, 10, addr 解大小) == 成功:
      var 解 = newSeq[H3索引](解大小)
      if 解紧凑单元(addr 紧凑[0], 7, addr 解[0], 解大小, 10) == 成功:
        let 有效解 = 解.countIt(it != H3空)
        echo &"解紧凑后: {有效解} 个单元 (期望 7)"

# ── 4. 网格距离 & 路径 ─────────────────────

echo "\n=== 网格距离与路径 ==="
let 上海 = 度转经纬度(31.2304, 121.4737)
let 单元2 = 上海.经纬度转单元(10)

var 距离: int64
if 网格距离(单元, 单元2, addr 距离) == 成功:
  echo &"北京→上海: {距离} 步 (网格距离)"

  var 路长: int64
  if 网格路径单元数(单元, 单元2, addr 路长) == 成功:
    var 路径 = newSeq[H3索引](路长)
    if 网格路径单元(单元, 单元2, addr 路径[0]) == 成功:
      echo &"路径长度: {路长} 个单元"
      # 首尾确认
      echo &"  起点: {单元转字符串(路径[0])}"
      echo &"  终点: {单元转字符串(路径[^1])}"

# ── 5. 有向边 ─────────────────────────────

echo "\n=== 有向边 ==="
var 邻居2: array[7, H3索引]
if 网格圆盘(单元, 1, addr 邻居2[0]) == 成功 and 邻居2[1] != H3空:
  var 边: H3索引
  if 单元转有向边(单元, 邻居2[1], addr 边) == 成功:
    echo &"边: {单元转字符串(边)}"
    echo &"  是否有效有向边: {是否有效有向边(边)}"

    # 起点终点
    var 起点, 终点: H3索引
    discard 获取有向边起点(边, addr 起点)
    discard 获取有向边终点(边, addr 终点)
    echo &"  起点: {单元转字符串(起点)}"
    echo &"  终点: {单元转字符串(终点)}"

    # 反转
    var 反转边: H3索引
    if 反转有向边(边, addr 反转边) == 成功:
      discard 获取有向边起点(反转边, addr 起点)
      discard 获取有向边终点(反转边, addr 终点)
      echo &"  反转后起点→终点: {单元转字符串(起点)} → {单元转字符串(终点)}"

# ── 6. 顶点 ───────────────────────────────

echo "\n=== 顶点 ==="
var 顶点集: array[6, H3索引]
if 单元转顶点集(单元, addr 顶点集[0]) == 成功:
  echo &"顶点数: {顶点集.countIt(it != H3空)}"
  for i in 0..<6:
    if 顶点集[i] != H3空:
      var 点: 经纬度
      if 顶点转经纬度(顶点集[i], addr 点) == 成功:
        let (lat, lng) = 点.经纬度转度()
        echo &"  顶点 {i}: ({lat:.6f}, {lng:.6f})"

# ── 7. 五边形检测 ─────────────────────────

echo "\n=== 五边形 ==="
var 五边 = newSeq[H3索引](12)
if 获取五边形(5, addr 五边[0]) == 成功:
  echo "res 5 五边形:"
  for i, p in 五边.pairs:
    if p != H3空:
      echo &"  {i}: {单元转字符串(p)}"
      break  # 只展示第一个

echo "\n✅ 层级与路径示例完成"

## 地理围栏示例：多边形区域内的 H3 单元覆盖
##
## 使用: nim c --path:src -r examples/example_geofence.nim

import std/strformat
import h3nim

# ── 工具：构造矩形多边形 / 释放 / 收集单元 ───────

proc 矩形多边形(南纬, 西经, 北纬, 东经: float64): 地理多边形 =
  ## 按逆时针顺序构造矩形地理多边形（参数为角度度）。
  const 边数 = 4
  var 环 = 地理环(
    顶点数: 边数,
    顶点: cast[ptr 经纬度](alloc0(sizeof(经纬度) * 边数)),
  )
  let 顶点 = cast[ptr array[边数, 经纬度]](环.顶点)
  顶点[0] = 度转经纬度(南纬, 西经)
  顶点[1] = 度转经纬度(南纬, 东经)
  顶点[2] = 度转经纬度(北纬, 东经)
  顶点[3] = 度转经纬度(北纬, 西经)
  地理多边形(外环: 环, 孔数: 0, 孔: nil)

proc 释放(多边形: var 地理多边形) =
  if 多边形.外环.顶点 != nil:
    dealloc(多边形.外环.顶点)
    多边形.外环.顶点 = nil

proc 收集单元(多边形: var 地理多边形, 分辨率: int): seq[H3索引] =
  ## `多边形转单元` 封装已内部过滤掉哈希空洞产生的 H3空。
  多边形转单元(多边形, 分辨率)

# ── 1. 故宫区域的多分辨率覆盖 ─────────────────

echo "=== 故宫区域 H3 覆盖 ==="
var 故宫 = 矩形多边形(39.9070, 116.3970, 39.9150, 116.4030)
for 分辨率 in [8, 9, 10]:
  let 单元列表 = 收集单元(故宫, 分辨率)
  echo &"res {分辨率}: {单元列表.len} 个单元"
  for 单元 in 单元列表[0 ..< min(单元列表.len, 5)]:
    echo "  ", 单元转字符串(单元)
故宫.释放()

# ── 2. 点包含检测 ────────────────────────────

echo "\n=== 点包含检测（res 13 高精度覆盖）==="
var 故宫高精度 = 矩形多边形(39.9070, 116.3970, 39.9150, 116.4030)
let 覆盖集 = 收集单元(故宫高精度, 13)
echo &"故宫 res 13 覆盖: {覆盖集.len} 个六边形"

let 午门 = 经纬度转单元(度转经纬度(39.9093, 116.3972), 13)
let 国贸 = 经纬度转单元(度转经纬度(39.9082, 116.4605), 13)
echo &"午门({单元转字符串(午门)}) 在故宫内: {午门 in 覆盖集}"
echo &"国贸({单元转字符串(国贸)}) 在故宫内: {国贸 in 覆盖集}"
故宫高精度.释放()

# ── 3. 用实验性 API（连续输出）等价实现 ───────

echo "\n=== 实验性 polygonToCellsExperimental（连续输出）==="
var 故宫实验 = 矩形多边形(39.9070, 116.3970, 39.9150, 116.4030)
block:
  let 缓冲 = 多边形转单元实验(故宫实验, 9)
  echo &"res 9: {缓冲.len} 个单元（连续排列）"
  for i in 0 ..< min(缓冲.len, 5):
    echo "  ", 单元转字符串(缓冲[i])
故宫实验.释放()

# ── 4. 大范围区域统计 ────────────────────────

echo "\n=== 北京市粗略覆盖统计 ==="
var 北京 = 矩形多边形(39.70, 116.10, 40.25, 116.75)
let 覆盖7 = 收集单元(北京, 7)
echo &"res 7: {覆盖7.len} 个六边形 (~{覆盖7.len * 23} km²)"
北京.释放()

echo "\n✅ 地理围栏示例完成"

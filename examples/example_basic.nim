## 基础示例：经纬度 ↔ H3 索引、k-ring、距离计算
##
## 使用: nim c --path:src -r examples/example_basic.nim

import std/[strformat, sequtils]
import h3nim

# ── 1. 经纬度 → H3 索引 ─────────────────────────

echo "=== 1. 经纬度 → H3 索引 ==="
let 北京 = 度转经纬度(39.9042, 116.4074)
let 单元 = 北京.经纬度转单元(12)
echo "北京(天安门) @ res 12: ", 单元转字符串(单元)

# 不同分辨率
for 分辨率 in [0, 5, 10, 15]:
  let 不同 = 北京.经纬度转单元(分辨率)
  echo &"  res {分辨率:2d}: {单元转字符串(不同)}"

# ── 2. H3 索引 → 经纬度（单元中心）───────────

echo "\n=== 2. 单元中心经纬度 ==="
let 中心 = 单元.单元转经纬度()
let (纬度, 经度) = 中心.经纬度转度()
echo &"单元中心: {纬度:.6f}, {经度:.6f}"

# ── 3. 单元边界顶点 ─────────────────────────

echo "\n=== 3. 单元边界 ==="
let 边界 = 单元转边界(单元)
echo &"顶点数: {边界.顶点数}"
for i in 0 ..< 边界.顶点数.int:
  let (vl, vn) = 边界.顶点[i].经纬度转度()
  echo &"  顶点 {i}: ({vl:.6f}, {vn:.6f})"

# ── 4. k-ring（邻居查找）────────────────────

echo "\n=== 4. k-ring 邻居 ==="
for k in 0 .. 3:
  let 邻居 = 网格圆盘(单元, k)
  let 有效数 = 邻居.countIt(it != H3空)
  echo &"k={k}: {有效数} 个单元"

# ── 4b. 网格环与带距离的圆盘 ───────────────

echo "\n=== 网格环与带距离的圆盘 ==="
for k in 1 .. 2:
  let 环 = 网格环(单元, k)
  echo &"k={k} 环上 {环.countIt(it != H3空)} 个单元"
let 带距离 = 网格圆盘距离(单元, 1)
echo "1-ring 距离: ", 带距离[0 .. 2]

# ── 5. 大圆距离 ────────────────────────────

echo "\n=== 5. 大圆距离 ==="
let 上海 = 度转经纬度(31.2304, 121.4737)
let 东京 = 度转经纬度(35.6762, 139.6503)
echo &"上海→东京: {大圆距离千米(上海, 东京):.1f} km"
echo &"上海→东京: {大圆距离米(上海, 东京):.0f} m"
echo &"上海→东京: {大圆距离弧度(上海, 东京):.6f} rad"

# ── 6. 属性查询 ────────────────────────────

echo "\n=== 6. 单元属性 ==="
echo &"分辨率:     {获取分辨率(单元)}"
echo &"基单元号:   {获取基单元号(单元)}"
echo &"是否有效:   {是否有效单元(单元)}"
echo &"是否五边形: {是否五边形(单元)}"
echo &"是否三级类: {是否三级类(单元)}"

# ── 7. 零级单元列举 ───────────────────────

echo "\n=== 7. 零级单元 ==="
let 零级 = 获取零级单元()
echo &"零级单元总数: {零级.len}"
echo &"其中五边形: {零级.countIt(是否五边形(it))}"

# ── 8. 面积与边长 ──────────────────────────

echo "\n=== 8. 面积与边长 ==="
echo &"单元面积: {单元面积平方千米(单元):.6f} km² / {单元面积平方米(单元):.0f} m²"
echo &"平均面积 (res 9): {获取六边形平均面积平方千米(9):.4f} km²"
echo &"平均边长 (res 9): {获取六边形平均边长千米(9):.4f} km"

echo "\n✅ 基础示例完成"

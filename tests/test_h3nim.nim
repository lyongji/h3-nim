## H3 Nim 绑定单元测试
##
## ponytail: 轻量自检，无需测试框架。失败时 assert 终止并提供中文描述。

import std/[math, strformat]
import h3nim

# ── 辅助 ──

var 通过 = 0
var 失败 = 0

template 测试*(name: string, body: untyped) =
  try:
    body
    通过 += 1
  except CatchableError as e:
    失败 += 1
    stderr.writeLine "[失败] " & name & ": " & e.msg

proc 近似相等(a, b: float64, 容差 = 1e-6): bool = abs(a - b) < 容差

# ── 测试用例 ──

测试 "经纬度 ↔ 单元 往返":
  let 旧金山 = 度转经纬度(37.7749, -122.4194)
  let 单元 = 经纬度转单元(旧金山, 10)
  assert 单元 != H3空, "经纬度转单元返回空"
  let 中心 = 单元转经纬度(单元)
  let (纬度, 经度) = 经纬度转度(中心)
  assert 近似相等(纬度, 37.7749, 0.01), &"纬度偏差: {纬度}"
  assert 近似相等(经度, -122.4194, 0.01), &"经度偏差: {经度}"

测试 "单元转字符串 往返":
  let 单元 = 字符串转单元("8928308280fffff")
  assert 单元 != H3空
  let 串 = 单元转字符串(单元)
  assert 串 == "8928308280fffff", &"字符串不匹配: {串}"

测试 "是否有效单元":
  let 有效 = 字符串转单元("8928308280fffff")
  assert 是否有效单元(有效), "有效单元被判无效"
  assert not 是否有效单元(H3空), "H3_NULL 被判有效"

测试 "获取分辨率":
  let 单元 = 字符串转单元("8928308280fffff")
  assert 获取分辨率(单元) == 9, &"分辨率应为 9，实际 {获取分辨率(单元)}"

测试 "网格圆盘 (k-ring)":
  let 单元 = 字符串转单元("8928308280fffff")
  var 邻居: array[7, H3索引]
  let 错误 = 网格圆盘(单元, 1, addr 邻居[0])
  assert 错误 == 成功, &"网格圆盘失败: {描述H3错误(错误)}"
  assert 邻居[0] == 单元, "k-ring 首个应为原点"
  var 有效数 = 0
  for 邻 in 邻居:
    if 邻 != H3空: 有效数 += 1
  assert 有效数 == 7, &"1-ring 应有 7 个有效单元，实际 {有效数}"

测试 "大圆距离":
  let 旧金山 = 度转经纬度(37.7749, -122.4194)
  let 洛杉矶 = 度转经纬度(34.0522, -118.2437)
  let 距离 = 大圆距离千米(addr 旧金山, addr 洛杉矶)
  assert 距离 > 500 and 距离 < 600, &"旧金山→洛杉矶距离异常: {距离} km"

测试 "零级单元数":
  let 数 = 零级单元数()
  assert 数 == 122, &"零级单元数应为 122，实际 {数}"

测试 "单元数":
  var 数: int64
  let 错误 = 获取单元数(0, addr 数)
  assert 错误 == 成功
  assert 数 == 122, &"res 0 应有 122 单元，实际 {数}"
  discard 获取单元数(1, addr 数)
  assert 数 == 842, &"res 1 应有 842 单元，实际 {数}"

测试 "是否五边形":
  # 零级五边形索引示例
  let 五边 = 字符串转单元("8009fffffffffff")  # 一个五边形
  # 验证至少有一个五边形
  var 五边列表: array[12, H3索引]
  discard 获取五边形(0, addr 五边列表[0])
  assert 五边列表[0] != H3空

测试 "是否三级类":
  let 单元 = 字符串转单元("8928308280fffff")
  let 三级 = 是否三级类(单元)
  assert 三级 == false or 三级 == true  # 布尔值即可

测试 "度转弧度 往返":
  let 原始度 = 45.0
  let 弧度 = 度转弧度(原始度)
  let 结果度 = 弧度转度(弧度)
  assert 近似相等(结果度, 45.0), &"度→弧度→度 不匹配: {结果度}"

测试 "单元面积":
  let 单元 = 字符串转单元("8928308280fffff")
  var 面积: float64
  let 错误 = 单元面积平方千米(单元, addr 面积)
  assert 错误 == 成功, &"单元面积失败: {描述H3错误(错误)}"

测试 "有向边":
  let 原点 = 字符串转单元("8928308280fffff")
  var 邻居: array[7, H3索引]
  if 网格圆盘(原点, 1, addr 邻居[0]) == 成功:
    if 邻居[1] != H3空:
      var 边: H3索引
      let 错误 = 单元转有向边(原点, 邻居[1], addr 边)
      if 错误 == 成功:
        assert 是否有效有向边(边)

测试 "父级/子级":
  let 父 = 字符串转单元("8928308280fffff")
  var 子: H3索引
  let 错误 = 单元转中心子级(父, 10, addr 子)
  assert 错误 == 成功, &"单元转中心子级失败: {描述H3错误(错误)}"
  assert 子 != H3空
  var 父还原: H3索引
  discard 单元转父级(子, 9, addr 父还原)
  assert 父还原 == 父, "父→子→父 不相等"

测试 "错误码比较与描述":
  let 成功错误 = H3错误(0)
  assert 成功错误 == 成功
  assert 成功 == 成功错误
  assert 是否成功(成功错误)

  let 域错误码 = H3错误(4)
  assert 域错误码 == 分辨率域错误
  assert 分辨率域错误 == 域错误码
  assert 域错误码 != 成功
  assert not 是否成功(域错误码)
  assert $域错误码 == $描述H3错误(域错误码), "$错误 应返回可读描述"

# ── 结果 ──

echo &"\n测试完成: {通过} 通过, {失败} 失败"
if 失败 > 0:
  quit(1)
